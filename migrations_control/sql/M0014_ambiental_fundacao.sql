CREATE TABLE amb_normas_versoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    identificador_publico UUID NOT NULL,
    codigo TEXT NOT NULL,
    titulo TEXT NOT NULL,
    descricao TEXT,
    vigencia_inicio DATE NOT NULL,
    vigencia_fim DATE,
    estado TEXT NOT NULL DEFAULT 'RASCUNHO',
    fonte_nome TEXT,
    fonte_sha256 VARCHAR(64),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    criado_por_usuario_id INTEGER,
    atualizado_por_usuario_id INTEGER,
    versao_registro INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE amb_cnaes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    versao_cnae TEXT NOT NULL,
    codigo VARCHAR(7) NOT NULL,
    descricao TEXT NOT NULL,
    secao VARCHAR(1),
    divisao VARCHAR(2),
    grupo VARCHAR(3),
    classe VARCHAR(5),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE amb_classificacoes_cnae (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    norma_versao_id BIGINT NOT NULL,
    cnae_id BIGINT NOT NULL,
    origem_enquadramento TEXT NOT NULL,
    classificacao_direta TEXT,
    pode_baixo_a BOOLEAN NOT NULL DEFAULT FALSE,
    pode_moderado BOOLEAN NOT NULL DEFAULT FALSE,
    pode_alto BOOLEAN NOT NULL DEFAULT FALSE,
    observacao TEXT,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE amb_quesitos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    norma_versao_id BIGINT NOT NULL,
    codigo VARCHAR(10) NOT NULL,
    numero INTEGER NOT NULL,
    texto TEXT NOT NULL,
    ordem INTEGER NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE amb_classificacao_quesitos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    classificacao_id BIGINT NOT NULL,
    quesito_id BIGINT NOT NULL,
    ordem INTEGER,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE amb_perfis_controle (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    norma_versao_id BIGINT NOT NULL,
    codigo VARCHAR(10) NOT NULL,
    nivel INTEGER NOT NULL,
    nome TEXT NOT NULL,
    descricao TEXT,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE amb_estabelecimentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    identificador_publico UUID NOT NULL,
    tipo_pessoa TEXT NOT NULL DEFAULT 'JURIDICA',
    cnpj VARCHAR(14),
    cpf VARCHAR(11),
    nome_razao_social TEXT NOT NULL,
    nome_fantasia TEXT,
    inscricao_municipal TEXT,
    inscricao_estadual TEXT,
    cep VARCHAR(8),
    logradouro TEXT,
    numero TEXT,
    complemento TEXT,
    bairro TEXT,
    cidade TEXT,
    uf VARCHAR(2),
    latitude NUMERIC(9,6),
    longitude NUMERIC(9,6),
    telefone TEXT,
    email TEXT,
    estado TEXT NOT NULL DEFAULT 'ATIVO',
    origem TEXT NOT NULL DEFAULT 'MANUAL',
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    criado_por_usuario_id INTEGER NOT NULL,
    atualizado_por_usuario_id INTEGER,
    versao_registro INTEGER NOT NULL DEFAULT 1,
    request_id UUID NOT NULL
);

CREATE TABLE amb_estabelecimento_cnaes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    estabelecimento_id BIGINT NOT NULL,
    cnae_id BIGINT NOT NULL,
    principal BOOLEAN NOT NULL DEFAULT FALSE,
    vigente_desde DATE NOT NULL DEFAULT CURRENT_DATE,
    vigente_ate DATE,
    estado TEXT NOT NULL DEFAULT 'ATIVO',
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    criado_por_usuario_id INTEGER NOT NULL,
    request_id UUID NOT NULL
);

