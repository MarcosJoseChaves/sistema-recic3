    ADD CONSTRAINT ck_amb_class_cnae__direta_coerente
    CHECK (
        classificacao_direta IS NULL
        OR (
            classificacao_direta = 'BAIXO_A'
            AND pode_baixo_a
            AND NOT pode_moderado
            AND NOT pode_alto
        )
        OR (
            classificacao_direta = 'MODERADO'
            AND NOT pode_baixo_a
            AND pode_moderado
            AND NOT pode_alto
        )
        OR (
            classificacao_direta = 'ALTO'
            AND NOT pode_baixo_a
            AND NOT pode_moderado
            AND pode_alto
        )
    );

