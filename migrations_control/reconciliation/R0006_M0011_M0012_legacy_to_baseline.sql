-- M0011: seeds estruturais RECEITA/DESPESA.
DO $r0006_seeds$
DECLARE
    v_codigo TEXT;
    v_total INTEGER;
    v_seguro INTEGER;
BEGIN
    FOREACH v_codigo IN ARRAY ARRAY['RECEITA', 'DESPESA'] LOOP
        SELECT count(*), count(*) FILTER (WHERE codigo = v_codigo
                                          AND nome = v_codigo
                                          AND nome_normalizado = lower(v_codigo)
                                          AND estado = 'ATIVO')
          INTO v_total, v_seguro
          FROM public.naturezas_financeiras
         WHERE codigo = v_codigo OR nome_normalizado = lower(v_codigo);
        IF v_total = 0 THEN
            INSERT INTO public.naturezas_financeiras (codigo, nome, nome_normalizado)
            VALUES (v_codigo, v_codigo, lower(v_codigo));
        ELSIF v_total <> 1 OR v_seguro <> 1 THEN
            RAISE EXCEPTION 'R0006/NATUREZA: colisao incompatível para %', v_codigo;
        END IF;
    END LOOP;
END
