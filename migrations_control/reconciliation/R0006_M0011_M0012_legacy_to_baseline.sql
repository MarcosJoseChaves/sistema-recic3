DO $r0006_associacoes$
DECLARE
    v_usuario_id INTEGER;
    v_invalidas INTEGER;
BEGIN
    SELECT id
      INTO STRICT v_usuario_id
      FROM public.usuarios
     WHERE username = 'migracao_dados_legados'
       AND username_normalizado = 'migracao_dados_legados'
       AND estado = 'BLOQUEADO'
       AND ativo = FALSE;

    WITH legacy_pairs AS (
        SELECT lower(btrim(tf.associacao)) AS token_normalizado,
               btrim(tf.associacao) AS sigla_historica,
               lower(btrim(tf.uvr)) AS uvr_legada,
               count(*) AS quantidade_transacoes
          FROM public.transacoes_financeiras AS tf
         GROUP BY 1, 2, 3
    ), legacy_identity AS (
        SELECT token_normalizado,
               count(*) AS pares_legacy,
               count(DISTINCT sigla_historica) AS siglas_historicas,
               count(DISTINCT uvr_legada) AS uvrs_legacy
          FROM legacy_pairs
         GROUP BY token_normalizado
    ), uvr_identity AS (
        SELECT uvr_legada, count(DISTINCT token_normalizado) AS tokens_por_uvr
          FROM legacy_pairs
         GROUP BY uvr_legada
    ), canonical_candidates AS (
        SELECT li.token_normalizado, a.id AS associacao_id
          FROM legacy_identity AS li
          JOIN public.associacoes AS a ON lower(btrim(a.codigo)) = li.token_normalizado
        UNION
        SELECT li.token_normalizado, a.id AS associacao_id
          FROM legacy_identity AS li
          JOIN public.associacoes AS a ON a.nome_normalizado = li.token_normalizado
        UNION
        SELECT li.token_normalizado, aa.associacao_id
          FROM legacy_identity AS li
          JOIN public.associacao_aliases AS aa ON aa.alias_normalizado = li.token_normalizado
    ), candidate_counts AS (
        SELECT token_normalizado, count(*) AS candidate_count
          FROM canonical_candidates GROUP BY token_normalizado
    ), divergent_codes AS (
        SELECT DISTINCT li.token_normalizado, a.id AS associacao_id
          FROM legacy_identity AS li
          JOIN public.associacoes AS a
            ON a.nome_normalizado = li.token_normalizado
            OR EXISTS (
                SELECT 1 FROM public.associacao_aliases AS aa
                 WHERE aa.associacao_id = a.id
                   AND aa.alias_normalizado = li.token_normalizado
            )
         WHERE a.codigo IS NOT NULL AND btrim(a.codigo) <> ''
           AND lower(btrim(a.codigo)) <> li.token_normalizado
    )
    SELECT count(*)
      INTO v_invalidas
      FROM legacy_identity AS li
      LEFT JOIN legacy_pairs AS lp
        ON lp.token_normalizado = li.token_normalizado AND li.pares_legacy = 1
      LEFT JOIN uvr_identity AS ui ON ui.uvr_legada = lp.uvr_legada
      LEFT JOIN candidate_counts AS cc ON cc.token_normalizado = li.token_normalizado
     WHERE li.token_normalizado IS NULL OR li.token_normalizado = ''
        OR li.siglas_historicas <> 1 OR li.uvrs_legacy <> 1
        OR COALESCE(ui.tokens_por_uvr, 0) <> 1
        OR COALESCE(cc.candidate_count, 0) > 1
        OR EXISTS (SELECT 1 FROM divergent_codes AS dc
                    WHERE dc.token_normalizado = li.token_normalizado);

    IF v_invalidas <> 0 THEN
        RAISE EXCEPTION 'R0006/ASSOCIACAO: identidade legacy ou candidato canonico ambiguo/incompativel';
    END IF;

    WITH legacy_pairs AS (
        SELECT lower(btrim(tf.associacao)) AS token_normalizado,
               btrim(tf.associacao) AS sigla_historica,
               lower(btrim(tf.uvr)) AS uvr_legada,
               count(*) AS quantidade_transacoes
          FROM public.transacoes_financeiras AS tf
         GROUP BY 1, 2, 3
    ), legacy_identity AS (
        SELECT token_normalizado, count(*) AS pares_legacy,
               count(DISTINCT sigla_historica) AS siglas_historicas,
               count(DISTINCT uvr_legada) AS uvrs_legacy
          FROM legacy_pairs GROUP BY token_normalizado
    ), canonical_candidates AS (
        SELECT li.token_normalizado, a.id AS associacao_id
          FROM legacy_identity AS li
          JOIN public.associacoes AS a ON lower(btrim(a.codigo)) = li.token_normalizado
        UNION
        SELECT li.token_normalizado, a.id AS associacao_id
          FROM legacy_identity AS li
          JOIN public.associacoes AS a ON a.nome_normalizado = li.token_normalizado
        UNION
        SELECT li.token_normalizado, aa.associacao_id
          FROM legacy_identity AS li
          JOIN public.associacao_aliases AS aa ON aa.alias_normalizado = li.token_normalizado
    ), candidate_counts AS (
        SELECT token_normalizado, count(*) AS candidate_count
          FROM canonical_candidates GROUP BY token_normalizado
    )
    INSERT INTO public.associacoes (
        codigo, nome, nome_normalizado, descricao, estado, inicio_data,
        criado_por_usuario_id, atualizado_por_usuario_id
    )
    SELECT lp.sigla_historica, lp.sigla_historica, lp.token_normalizado,
           NULL, 'EM_IMPLANTACAO', CURRENT_DATE, v_usuario_id, v_usuario_id
      FROM legacy_pairs AS lp
      JOIN legacy_identity AS li
        ON li.token_normalizado = lp.token_normalizado
       AND li.pares_legacy = 1 AND li.siglas_historicas = 1 AND li.uvrs_legacy = 1
      LEFT JOIN candidate_counts AS cc ON cc.token_normalizado = lp.token_normalizado
     WHERE COALESCE(cc.candidate_count, 0) = 0;

    WITH legacy_tokens AS (
        SELECT DISTINCT lower(btrim(tf.associacao)) AS token_normalizado
          FROM public.transacoes_financeiras AS tf
    ), canonical_candidates AS (
        SELECT lt.token_normalizado, a.id AS associacao_id
          FROM legacy_tokens AS lt
          JOIN public.associacoes AS a ON lower(btrim(a.codigo)) = lt.token_normalizado
        UNION
        SELECT lt.token_normalizado, a.id AS associacao_id
          FROM legacy_tokens AS lt
          JOIN public.associacoes AS a ON a.nome_normalizado = lt.token_normalizado
        UNION
        SELECT lt.token_normalizado, aa.associacao_id
          FROM legacy_tokens AS lt
          JOIN public.associacao_aliases AS aa ON aa.alias_normalizado = lt.token_normalizado
    ), candidate_counts AS (
        SELECT token_normalizado, count(*) AS candidate_count
          FROM canonical_candidates GROUP BY token_normalizado
    )
    SELECT count(*)
      INTO v_invalidas
      FROM legacy_tokens AS lt
      LEFT JOIN candidate_counts AS cc ON cc.token_normalizado = lt.token_normalizado
     WHERE COALESCE(cc.candidate_count, 0) <> 1;

    IF v_invalidas <> 0 THEN
        RAISE EXCEPTION 'R0006/ASSOCIACAO: cardinalidade canonica final diferente de 1';
    END IF;
END
